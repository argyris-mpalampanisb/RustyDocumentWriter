/// One UI colour theme.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Palette {
    pub name: &'static str,
    /// Where the theme comes from ("Word", "VS Code", "Zed").
    pub source: &'static str,
    pub dark: bool,
    /// Title bar and status bar.
    pub bg: Color32,
    /// Behind the pages.
    pub canvas: Color32,
    pub ribbon: Color32,
    pub hover: Color32,
    pub pressed: Color32,
    pub checked: Color32,
    pub sep: Color32,
    pub text: Color32,
    pub text_dim: Color32,
    pub text_disabled: Color32,
    pub icon: Color32,
    /// Filled buttons and selections (white text sits on it).
    pub accent: Color32,
    /// Links and highlighted labels.
    pub accent_text: Color32,
    pub field: Color32,
    /// Popups, menus and dialogs.
    pub window: Color32,
    pub backstage_side: Color32,
    pub backstage: Color32,
}

impl Palette {
    /// A border that stands out more than `sep` (checked buttons, focused boxes).
    pub fn border(&self) -> Color32 {
        self.sep.lerp_to_gamma(self.text, 0.3)
    }
}

const fn rgb(r: u8, g: u8, b: u8) -> Color32 {
    Color32::from_rgb(r, g, b)
}

